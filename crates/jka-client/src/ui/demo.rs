//! Demo playback HUD. Native UI geometry, using the same Taffy tree for drawing
//! and hit testing. Deliberately not an export editor: Render Studio owns that.
use crate::ui::{
    demo_timeline_layout, flex, rect, rect_gradient, rect_outline, text::UiText,
    truncate_jka_text, UiSnapshot, UiVertex,
};

type Color = [f32; 4];
const WHITE: Color = [0.95, 0.97, 1.0, 1.0];
const MUTED: Color = [0.62, 0.72, 0.81, 1.0];
const CYAN: Color = [0.37, 0.82, 1.0, 1.0];
const GOLD: Color = [1.0, 0.77, 0.40, 1.0];

fn label(
    out: &mut Vec<UiVertex>, font: &UiText<'_>, bounds: [f32; 4],
    value: &str, size: f32, color: Color, centered: bool,
) {
    let width = font.width(value, size);
    let x = if centered { bounds[0] + (bounds[2] - width) * 0.5 } else { bounds[0] };
    font.draw(out, value, x, font.baseline_in(bounds, size), size, color);
}

// Compact, readable Studio transport buttons. Small footprint is not a
// license for tiny labels: scale typography up and shorten long captions.
fn button(
    out: &mut Vec<UiVertex>, font: &UiText<'_>, bounds: [f32; 4],
    value: &str, active: bool, hovered: bool, primary: bool, scale: f32, w: u32, h: u32,
) {
    let [x, y, bw, bh] = bounds;
    let fill = if primary && active { [0.10, 0.38, 0.47, 0.97] }
        else if active { [0.10, 0.23, 0.30, 0.96] }
        else if hovered { [0.15, 0.22, 0.30, 0.97] }
        else { [0.075, 0.11, 0.17, 0.95] };
    rect(out, x, y, bw, bh, fill, w, h);
    rect_outline(out, x, y, bw, bh, 1.0,
        if hovered { [0.35, 0.73, 0.86, 0.85] }
        else if active { [0.29, 0.64, 0.78, 0.65] }
        else { [0.25, 0.34, 0.44, 0.63] }, w, h);
    if primary && active {
        rect(out, x + 1.0, y + 1.0, 3.0, (bh - 2.0).max(0.0), CYAN, w, h);
    }
    let nominal = 25.0 * scale;
    let size = (nominal * ((bw - 12.0) / font.width(value, nominal).max(1.0)).min(1.0))
        .max(20.0 * scale);
    label(out, font, bounds, value, size,
        if active || hovered { WHITE } else { [0.84, 0.90, 0.96, 1.0] }, true);
}

pub(in crate::ui) fn build_demo_timeline(out: &mut Vec<UiVertex>, ui: &UiSnapshot, w: u32, h: u32) {
    let Some(state) = &ui.demo_timeline else { return; };
    let Some(layout) = demo_timeline_layout(w, h, state.players.len(), state.player_scroll, state.player_open) else { return; };
    let font = UiText::new(ui, None, w, h);
    let type_scale = ((h as f32) / 900.0).clamp(0.95, 1.18);
    let hover = |bounds: [f32; 4]| state.hover_point.is_some_and(|p| flex::contains(bounds, p));

    if state.outside_authoritative_view {
        rect(out, 0.0, 0.0, w as f32, h as f32, [0.55, 0.0, 0.0, 0.14], w, h);
        font.draw(out, "OUTSIDE RECORDED PVS / PORTAL VISIBILITY", 24.0,
            font.cap(19.0) + 18.0, 19.0, [1.0, 0.65, 0.65, 1.0]);
    }

    // Render Studio transport: narrow dock, near-full-height typography.
    // All interactive positions are generated by the shared Taffy layout.
    let [x, y, pw, ph] = layout.panel;
    rect(out, x + 3.0, y + 5.0, pw, ph, [0.0, 0.0, 0.0, 0.36], w, h);
    rect_gradient(out, x, y, pw, ph,
        [0.045, 0.070, 0.10, 0.96], [0.055, 0.082, 0.12, 0.96],
        [0.018, 0.031, 0.052, 0.97], [0.025, 0.038, 0.062, 0.97], w, h);
    rect_outline(out, x, y, pw, ph, 1.0, [0.28, 0.40, 0.51, 0.92], w, h);
    rect(out, x, y, pw, 2.0, [0.30, 0.72, 0.92, 0.83], w, h);

    // Larger physical glyphs: UiText sizes specify line height, not cap height.
    label(out, &font, layout.title, "DEMO", 26.0 * type_scale, WHITE, false);
    let camera_px = 23.0 * type_scale;
    let max_camera = ((layout.camera[2] / (camera_px * 0.53)).floor() as usize).clamp(5, 80);
    label(out, &font, layout.camera, &truncate_jka_text(&state.camera_label, max_camera),
        camera_px, if state.free_view { GOLD } else { CYAN }, false);
    label(out, &font, layout.current,
        &format_demo_time(if let Some(f) = state.scrub_fraction {
            (state.duration_ms as f32 * f).round() as i32
        } else { state.elapsed_ms.round() as i32 }), 24.0 * type_scale, WHITE, true);
    label(out, &font, layout.total,
        &format!("/ {}", format_demo_time(state.duration_ms)), 21.0 * type_scale, MUTED, true);

    let [tx, ty, tw, th] = layout.track;
    let duration = state.duration_ms.max(1) as f64;
    let live = (state.elapsed_ms / duration).clamp(0.0, 1.0) as f32;
    let fraction = state.scrub_fraction.unwrap_or(live).clamp(0.0, 1.0);
    let rail_y = ty + th * 0.5 - 3.0;
    rect(out, tx, rail_y, tw, 6.0, [0.015, 0.035, 0.056, 1.0], w, h);
    rect_outline(out, tx, rail_y, tw, 6.0, 1.0, [0.27, 0.38, 0.48, 0.85], w, h);
    // Played portion, and a subtle scanline glint along the center of the rail.
    rect_gradient(out, tx + 1.0, rail_y + 1.0, (tw * fraction - 1.0).max(0.0), 4.0,
        [0.19, 0.54, 0.83, 1.0], [0.42, 0.81, 1.0, 1.0],
        [0.16, 0.39, 0.72, 1.0], [0.30, 0.65, 0.92, 1.0], w, h);
    for step in 1..10 {
        let tick_x = tx + tw * step as f32 / 10.0;
        rect(out, tick_x, rail_y - 4.0, 1.0, 3.0, [0.51, 0.64, 0.77, 0.55], w, h);
    }
    for marker in &state.kill_markers {
        let involved = marker.followed_kill || marker.followed_death;
        let marker_h = if involved { 21.0 } else { 12.0 };
        let marker_w = if involved { 3.0 } else { 2.0 };
        let color = match marker.attacker_team {
            1 => [1.0, 0.36, 0.40, 0.99],
            2 => [0.32, 0.62, 1.0, 0.99],
            _ => [1.0, 0.79, 0.37, 0.99],
        };
        let at = tx + tw * marker.fraction.clamp(0.0, 1.0) - marker_w * 0.5;
        rect(out, at, ty + (th - marker_h) * 0.5, marker_w, marker_h, color, w, h);
        if involved {
            rect(out, at - 1.0, ty + (th - marker_h) * 0.5, marker_w + 2.0, 2.0, WHITE, w, h);
        }
    }
    let thumb = tx + tw * fraction;
    rect(out, thumb - 6.0, ty + 2.0, 12.0, th - 4.0, [0.08, 0.22, 0.31, 0.70], w, h);
    rect(out, thumb - 3.0, ty + 1.0, 6.0, th - 2.0, WHITE, w, h);
    rect(out, thumb - 1.0, ty + 3.0, 2.0, th - 6.0, [0.27, 0.72, 0.92, 1.0], w, h);

    button(out, &font, layout.back, "-5s", false, hover(layout.back), false, type_scale, w, h);
    button(out, &font, layout.play, if state.paused { "PLAY" } else { "PAUSE" },
        true, hover(layout.play), true, type_scale, w, h);
    button(out, &font, layout.forward, "+5s", false, hover(layout.forward), false, type_scale, w, h);
    let recorded_active = state.players.iter().any(|p| p.recorded && p.active);
    button(out, &font, layout.recorded, "REC POV", recorded_active,
        hover(layout.recorded), false, type_scale, w, h);
    button(out, &font, layout.free, "FREECAM", state.free_view,
        hover(layout.free), false, type_scale, w, h);
    button(out, &font, layout.speed,
        &format!("{}x", state.playback_rate), false, hover(layout.speed), false, type_scale, w, h);

    // Flat browser like Render Studio: one pane header, quiet rows, compact
    // selected highlight, not a tall stack of glossy cards.
    if let (Some(panel), Some(header)) = (layout.player_panel, layout.player_header) {
        let [lx, ly, lw, lh] = panel;
        rect(out, lx + 2.0, ly + 3.0, lw, lh, [0.0, 0.0, 0.0, 0.25], w, h);
        rect(out, lx, ly, lw, lh, [0.065, 0.08, 0.13, 0.90], w, h);
        rect_outline(out, lx, ly, lw, lh, 1.0, [0.26, 0.31, 0.43, 0.73], w, h);
        let [hx, hy, hw, hh] = header;
        rect(out, hx, hy, hw, hh, [0.11, 0.14, 0.21, 0.95], w, h);
        rect(out, hx, hy + hh - 1.0, hw, 1.0, [0.19, 0.23, 0.33, 0.92], w, h);
        rect(out, hx + 9.0, hy + 7.0, 3.0, hh - 14.0, [1.0, 0.31, 0.59, 1.0], w, h);
        let head_label = [hx + 19.0, hy, hw - 103.0, hh];
        label(out, &font, head_label, "PLAYERS", 24.0 * type_scale, WHITE, false);
        let count = [hx + hw - 104.0, hy, 75.0, hh];
        label(out, &font, count, &format!("{} IN VIEW", state.players.len()),
            15.0 * type_scale, MUTED, true);
        let arrow = [hx + hw - 27.0, hy, 22.0, hh];
        label(out, &font, arrow, if state.player_open { "-" } else { "+" },
            25.0 * type_scale, WHITE, true);

        for (row, player) in layout.player_rows.iter().zip(state.players.iter().skip(layout.player_start)) {
            let [rx, ry, rw, rh] = *row;
            let hovered = hover(*row);
            if player.active || hovered {
                rect(out, rx + 4.0, ry + 1.0, rw - 8.0, rh - 2.0,
                    if player.active { [0.11, 0.29, 0.39, 0.97] }
                    else { [0.16, 0.21, 0.30, 0.91] }, w, h);
            }
            if player.active {
                rect(out, rx + 4.0, ry + 3.0, 3.0, rh - 6.0, CYAN, w, h);
            }
            // Studio list_row icon slot, followed by a full-size name.
            rect(out, rx + 13.0, ry + rh * 0.5 - 2.5, 5.0, 5.0,
                if player.active { CYAN } else if player.recorded { GOLD }
                else { [0.46, 0.57, 0.68, 1.0] }, w, h);
            let badge = if player.recorded { "REC" } else if player.active { "POV" } else { "" };
            let badge_px = 16.0 * type_scale;
            let badge_w = if badge.is_empty() { 0.0 } else { font.width(badge, badge_px) + 13.0 };
            let name_bounds = [rx + 29.0, ry, (rw - badge_w - 36.0).max(25.0), rh];
            let name_px = 24.0 * type_scale;
            let mut name = truncate_jka_text(&player.name, 48);
            while font.width(&name, name_px) > name_bounds[2]
                && crate::ui::visible_jka_chars(&name) > 3
            {
                name = truncate_jka_text(&player.name, crate::ui::visible_jka_chars(&name) - 1);
            }
            label(out, &font, name_bounds, &name, name_px,
                if player.active { WHITE } else { [0.84, 0.90, 0.96, 1.0] }, false);
            if !badge.is_empty() {
                let meta = [rx + rw - badge_w - 6.0, ry, badge_w, rh];
                label(out, &font, meta, badge, badge_px,
                    if player.recorded { GOLD } else { CYAN }, true);
            }
        }
        if let Some(footer) = layout.player_footer {
            let [fx, fy, fw, fh] = footer;
            rect(out, fx, fy, fw, 1.0, [0.24, 0.29, 0.40, 0.70], w, h);
            let hint = [fx + 10.0, fy, fw - 92.0, fh];
            label(out, &font, hint, "SCROLL TO BROWSE", 16.0 * type_scale, MUTED, false);
            let end = layout.player_start + layout.player_rows.len();
            let page = [fx + fw - 98.0, fy, 90.0, fh];
            label(out, &font, page,
                &format!("{}-{end} / {}", layout.player_start + usize::from(end > 0), state.players.len()),
                16.0 * type_scale, MUTED, true);
        }
    }

}

pub(in crate::ui) fn format_demo_time(ms: i32) -> String {
    let seconds = ms.max(0) / 1000;
    let hours = seconds / 3600;
    if hours > 0 {
        format!("{hours}:{:02}:{:02}", (seconds / 60) % 60, seconds % 60)
    } else {
        format!("{}:{:02}", seconds / 60, seconds % 60)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn taffy_demo_buttons_have_no_overlap_and_fit_on_screen() {
        for (w, h) in [(740, 480), (1280, 720), (1649, 928), (2560, 1440)] {
            let layout = demo_timeline_layout(w, h, 8, 3, true).unwrap();
            let buttons = [layout.back, layout.play, layout.forward, layout.recorded, layout.free, layout.speed];
            for (i, a) in buttons.iter().enumerate() {
                assert!(a[2] > 0.0 && a[3] > 0.0);
                assert!(a[0] >= 0.0 && a[0] + a[2] <= w as f32 + 1.0);
                for b in buttons.iter().skip(i + 1) {
                    assert!(a[0] + a[2] <= b[0], "buttons overlap at {w}x{h}: {a:?}, {b:?}");
                }
            }
            assert!(layout.track[2] > 200.0);
            for row in &layout.player_rows {
                assert!(row[1] + row[3] < layout.panel[1], "player list overlaps timeline");
            }
        }
    }

    #[test]
    fn collapsed_browser_retains_only_its_clickable_header() {
        let layout = demo_timeline_layout(1649, 928, 25, 0, false).unwrap();
        assert!(layout.player_header.is_some());
        assert!(layout.player_rows.is_empty());
        assert!(layout.player_footer.is_none());
        assert!(layout.panel[3] < 110.0, "compact transport must not obstruct gameplay");
        let full = demo_timeline_layout(1649, 928, 25, 0, true).unwrap();
        assert!(full.player_rows.len() <= 9);
        assert!(full.player_rows.len() > 0);
        assert!(full.player_panel.unwrap()[3] < layout.panel[1]);
    }

    #[test]
    fn long_lists_can_scroll_to_the_final_player() {
        let layout = demo_timeline_layout(1600, 900, 32, 31, true).unwrap();
        assert!(layout.player_start <= 31);
        assert!(31 < layout.player_start + layout.player_rows.len());
    }
}
