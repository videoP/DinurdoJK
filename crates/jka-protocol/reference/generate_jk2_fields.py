"""Extract wire descriptors from the pinned JK2MV source, without compiling it.

Usage: python reference/generate_jk2_fields.py D:/Code/jk2mv
The generated descriptors preserve upstream ordering and signed widths.
"""
from pathlib import Path
import re
import subprocess
import sys

REVISION = "7d601454c3db68492289d4d4e3dc30bff39e4246"
root = Path(sys.argv[1])
git = ["git", "-c", f"safe.directory={root.resolve().as_posix()}", "-C", str(root)]
revision = subprocess.check_output(
    git + ["rev-parse", "HEAD"], text=True
).strip()
if revision != REVISION:
    raise SystemExit(f"Expected JK2MV {REVISION}, got {revision}")
source = subprocess.check_output(
    git + ["show", f"{REVISION}:src/qcommon/msg.cpp"], text=True
)
output = [
    "// SPDX-License-Identifier: GPL-2.0-only",
    "// Wire descriptors derived from mvdevs/jk2mv src/qcommon/msg.cpp.",
    f"// Pinned commit: {REVISION}",
    "// Generated by reference/generate_jk2_fields.py; do not reorder fields.",
    "// See LICENSE-JK2MV for upstream licensing.",
    "",
]
for upstream, rust, macro in [
    ("entityStateFields15", "ENTITY_FIELDS_102", "NETF"),
    ("entityStateFields16", "ENTITY_FIELDS_104", "NETF"),
    ("playerStateFields15", "PLAYER_FIELDS_102", "PSF"),
    ("playerStateFields16", "PLAYER_FIELDS_104", "PSF"),
]:
    body = re.search(r"\b" + upstream + r"\[\]\s*=\s*\{(.*?)\n\};", source, re.S)[1]
    body = re.sub(r"/\*.*?\*/|//[^\n]*", "", body, flags=re.S)
    fields = re.findall(r"\{\s*" + macro + r"\(([^)]+)\),\s*([^}]+)\}", body)
    if len(fields) != body.count(macro + "(") or not fields:
        raise SystemExit(f"Could not extract all fields in {upstream}")
    output.append(f"pub const {rust}: &[(&str, i8)] = &[")
    for name, width in fields:
        width = width.strip().replace("GENTITYNUM_BITS", "10")
        if not re.fullmatch(r"-?\d+", width):
            raise SystemExit(f"Unknown field width: {width}")
        output.append(f'    ("{name.strip()}", {width}),')
    output.extend(["];", ""])
    print(f"{upstream}: {len(fields)} fields")
destination = Path(__file__).resolve().parents[1] / "src" / "jk2" / "fields.rs"
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text("\n".join(output), encoding="utf-8", newline="\n")
