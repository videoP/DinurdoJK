"""Generate semantic JK2 -> existing presentation IDs from pinned native sources.

No animation frames or physics are synthesized. JK2-only animation names get
stable extra presentation slots below the native 2048 animation toggle bit.
Usage: python crates/jka-protocol/reference/generate_jk2_presentation.py D:/Code/mvsdk
"""
from pathlib import Path
import re
import subprocess
import sys

repo = Path(__file__).resolve().parents[2]
sdk = Path(sys.argv[1])
revision = "4c7c463638192aead1ff3de8a88cc5de266bf3a2"
git = ["git", "-c", f"safe.directory={sdk.resolve().as_posix()}", "-C", str(sdk)]
assert subprocess.check_output(git + ["rev-parse", "HEAD"], text=True).strip() == revision

def upstream(path):
    return subprocess.check_output(git + ["show", f"{revision}:{path}"], text=True)

def clean(text):
    return re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)

def enum(text, typename):
    body = re.search(r"typedef\s+enum[^{}]*\{([^{}]*)\}\s*" + typename + r"\s*;", clean(text), re.S)[1]
    values = {}
    value = -1
    for token in body.split(","):
        token = token.strip()
        if not token:
            continue
        name, *explicit = token.split("=")
        name = name.strip()
        value = int(explicit[0].strip(), 0) if explicit else value + 1
        values[name] = value
    return values

def flags(text):
    values = {}
    for name, raw in re.findall(r"^#define\s+(EF_\w+)\s+([^\n]+)", clean(text), re.M):
        expr = raw.strip()
        if re.fullmatch(r"[0-9a-fA-FxX()<>\s]+", expr):
            values[name] = eval(expr, {"__builtins__": {}}, {})
    return values

native = repo / "jka-movement/vendor/openjk/codemp/game"
jk2_bg = upstream("code/game/bg_public.h")
jka_bg = (native / "bg_public.h").read_text()
jk2_anims = upstream("code/game/anims.h")
jka_animation_source = (repo / "jka-assets/src/animation.rs").read_text()
jka_anims = re.findall(r'"([A-Z0-9_]+)"', re.search(r'pub const ANIMATION_NAMES:.*?=\s*\[(.*?)\];', jka_animation_source, re.S)[1])
assert len(jka_anims) == 1543
animations = [enum(jk2_anims, "animNumber_1_02_t"), enum(jk2_anims, "animNumber_t")]
extra = sorted({name.removesuffix("_1_02") for table in animations for name in table
                if not name.startswith("MAX_") and name.removesuffix("_1_02") not in jka_anims})
target_anims = {name: i for i, name in enumerate(jka_anims + extra)}
assert len(target_anims) < 2048
header = ["// SPDX-License-Identifier: GPL-2.0-only",
          f"// Derived from MVSDK {revision} and the vendored OpenJK presentation enums.",
          "// Generated by jka-protocol/reference/generate_jk2_presentation.py.",
          "// See crates/jka-protocol/src/jk2/LICENSE-JK2MV.", ""]
lines = header[:]
for label, table in zip(["ANIMATIONS_102", "ANIMATIONS_104"], animations):
    vals = [target_anims[name.removesuffix("_1_02")] for name in table if not name.startswith("MAX_")]
    lines.append(f"pub const {label}: &[i32] = &[")
    lines.extend(f"    {v}, // {name}" for name, v in zip((n for n in table if not n.startswith("MAX_")), vals))
    lines.extend(["];", ""])

for typename, label in [("saberMoveName_t", "SABER_MOVES"), ("entity_event_t", "EVENTS"),
                        ("entityType_t", "ENTITY_TYPES"), ("meansOfDeath_t", "DEATH_CAUSES"),
                        ("persEnum_t", "PERSISTANT"), ("holdable_t", "HOLDABLES"),
                        ("pmtype_t", "MOVEMENT_TYPES"), ("forceHandAnims_t", "HAND_ANIMS"),
                        ("statIndex_t", "STATS"), ("powerup_t", "POWERUPS")]:
    a, b = enum(jk2_bg, typename), enum(jka_bg, typename)
    aliases = {"HANDEXTEND_FORCEGRIP": "HANDEXTEND_FORCE_HOLD"}
    vals = [(value, b.get(aliases.get(name, name), -1), name) for name, value in a.items() if value >= 0]
    lines.append(f"pub const {label}: &[i32] = &[")
    lines.extend(f"    {v}, // {name}" for _, v, name in sorted(vals))
    lines.extend(["];", ""])
a, b = enum(upstream("code/game/bg_weapons.h"), "weapon_t"), enum((native / "bg_weapons.h").read_text(), "weapon_t")
lines.append("pub const WEAPONS: &[i32] = &[")
lines.extend(f"    {b.get(name, -1)}, // {name}" for name in a)
lines.extend(["];", ""])
fa, fb = flags(jk2_bg), flags(jka_bg)
lines.append("pub const ENTITY_FLAGS: &[(u32, u32)] = &[")
lines.extend(f"    ({a:#x}, {fb[name]:#x}), // {name}" for name, a in fa.items() if name in fb)
lines.extend(["];", ""])

def items(text):
    text = clean(text).split("bg_itemlist[]", 1)[1].split("=", 1)[1]
    level = 0
    entries = []
    start = 0
    in_string = False
    escaped = False
    for i, char in enumerate(text):
        if in_string:
            if escaped: escaped = False
            elif char == "\\": escaped = True
            elif char == '"': in_string = False
            continue
        if char == '"': in_string = True
        elif char == "{":
            level += 1
            if level == 2: start = i
        elif char == "}":
            if level == 2:
                entry = text[start + 1:i].strip()
                m = re.match(r'"([^"\n]*)"', entry)
                entries.append(m[1] if m else "")
            level -= 1
            if level == 0: break
    return entries

ia = items(upstream("code/game/bg_misc.c"))
ib = items((native / "bg_misc.c").read_text())
assert ia[1] == ib[1] == "item_shield_sm_instant"
lines.append("pub const ITEMS: &[i32] = &[")
lines.extend(f"    {ib.index(name) if name in ib else -1}, // {name or '(null)'}" for name in ia)
lines.extend(["];", ""])
(repo / "jka-protocol/src/jk2/presentation_ids.rs").write_text("\n".join(lines), newline="\n")
extra_lines = header + ["pub const EXTRA_ANIMATION_NAMES: &[&str] = &["]
extra_lines.extend(f'    "{name}",' for name in extra)
extra_lines.extend(["];", ""])
(repo / "jka-assets/src/jk2_animation_names.rs").write_text("\n".join(extra_lines), newline="\n")
print(f"Presentation IDs generated; {len(extra)} exact JK2-only animation names, {len(target_anims)} total slots")
